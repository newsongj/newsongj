/**
 * 명단 화면 상단 필터 바의 공통 규격.
 *
 * 화면마다 `width={110}` / `{120}` / `{160}` 처럼 따로 적다 보니 폭이 제각각이 되어
 * 필터 줄이 들쭉날쭉해졌다. 값을 한 곳에 모아 어느 화면에서든 같은 크기로 보이게 한다.
 *
 * 쓰는 곳
 *   - 소견서 현황 대시보드  (기준 연도 · 교구 · 팀 · 그룹 · 작성 여부 · 이름 검색)
 *   - 팀배치 사전 설정      (배치 대상 연도)
 *   - 팀배치 작업          (배치 교구 · 배치 팀 · 이름 검색)
 *
 * 폭이 다른 컨트롤이 필요하면 여기에 항목을 추가하고, 페이지에서 숫자를 직접 쓰지 않는다.
 */
export const FILTER_SIZES = {
  /** 드롭다운 — 「2026년」 「전체 교구」 「작성 완료」 정도가 잘리지 않는 폭 */
  select: 130,
  /** 이름 검색 입력 — 돋보기 아이콘 + 한글 6~7자 */
  search: 200,
  /**
   * 좁은 화면에서 라벨이 차지하는 고정 폭.
   *
   * 「기준 연도」·「작성 여부」·「팀」처럼 라벨 길이가 제각각이면 남는 폭도 달라져
   * 컨트롤 너비가 들쭉날쭉해진다. 라벨 칸을 고정해야 컨트롤이 모두 같은 폭이 된다.
   * 가장 긴 라벨(「배치 대상 연도」)이 두 줄로 깨지지 않는 값이어야 한다.
   */
  labelColumn: 92,
} as const;

/**
 * 좁은 화면에서 필터를 세로로 펴는 기준점.
 *
 * `Select` 는 루트 `MuiFormControl` 에 폭을 **인라인으로** 박으므로,
 * 100% 로 펴려면 `!important` 가 필요하다.
 *
 * ```ts
 * [`@media (max-width: ${FILTER_STACK_BREAKPOINT}px)`]: {
 *   alignItems: 'stretch',
 *   '& .MuiFormControl-root': { width: '100% !important' },
 * }
 * ```
 */
export const FILTER_STACK_BREAKPOINT = 760;
